def _upgrade_sync() -> None:
    from alembic import command  # noqa: PLC0415
    from alembic.config import Config  # noqa: PLC0415

    config = Config(str(ALEMBIC_INI))
    config.set_main_option("script_location", str(ALEMBIC_INI.parent / "azzy" / "db" / "migrations"))
    command.upgrade(config, "head")


async def init_schema(retries: int = 30, delay: float = 2.0) -> None:
    """Run `alembic upgrade head`, retrying while Postgres is still starting up."""
    last: Exception | None = None
    for attempt in range(1, retries + 1):
        try:
            # alembic's env.py calls asyncio.run(); it must execute off the running loop.
            await asyncio.to_thread(_upgrade_sync)
            log.info("schema ready", extra={"fields": {"attempt": attempt}})
            return
        except Exception as exc:  # noqa: BLE001 - startup retry loop
            last = exc
            log.warning("database not ready", extra={"fields": {"attempt": attempt, "error": type(exc).__name__}})
            await asyncio.sleep(delay)
    raise RuntimeError(f"database unavailable after {retries} attempts: {last!r}")


async def seed() -> None:
    """Admin user, demo AWS accounts, environments, XP rows and seed runbooks. Idempotent."""
    settings = get_settings()
    async with session_scope() as session:
        # ---- admin user ------------------------------------------------------------------
        admin_email = settings.OWNER_EMAIL.strip().lower()
        admin = (await session.execute(select(UserRow).where(UserRow.email == admin_email))).scalar_one_or_none()
        seed_hash = owner_seed_hash(settings)
        if admin is None:
            session.add(UserRow(id=new_id(), email=admin_email, password_hash=seed_hash, role="admin", seed_hash=seed_hash, disabled=False))
        elif admin.seed_hash is not None and admin.password_hash == admin.seed_hash:
            # Never changed in-app → follow the env value when it changed.
            from azzy.auth import check_password, is_bcrypt_hash  # noqa: PLC0415

            env_changed = (not is_bcrypt_hash(settings.OWNER_PASSWORD) and not check_password(settings.OWNER_PASSWORD, admin.password_hash)) or (
                is_bcrypt_hash(settings.OWNER_PASSWORD) and settings.OWNER_PASSWORD != admin.password_hash
            )
            if env_changed:
                admin.password_hash = seed_hash
                admin.seed_hash = seed_hash
            admin.role = "admin"
            admin.disabled = False

        # ---- demo AWS accounts (DEMO only) ----------------------------------------------
        account_ids: dict[str, str] = {}
        if settings.DEMO:
            for spec in DEMO_ACCOUNTS:
                existing = await get_account_by_aws_id(session, str(spec["account_id"]))
                if existing is None:
                    existing = AwsAccountRow(
                        id=str(spec["id"]), name=str(spec["name"]), account_id=str(spec["account_id"]), role_arn=str(spec["role_arn"]),
                        external_id_enc=None, scope=str(spec["scope"]), regions=list(spec["regions"]), stage=str(spec["stage"]),
                        status="verified", permissions=[], last_verified=datetime.now(UTC), error=None, demo=True, created_by="system",
                    )
                    session.add(existing)
                    await session.flush()
                account_ids[str(spec["account_id"])] = existing.id

        # ---- environments ------------------------------------------------------------------
        existing_envs = {row.id: row for row in (await session.execute(select(EnvironmentRow))).scalars()}
        for spec in SEED_ENVIRONMENTS:
            linked = account_ids.get(str(spec["account_aws_id"])) if spec["account_aws_id"] else None
            if spec["id"] in existing_envs:
                row = existing_envs[str(spec["id"])]
                if row.account_id is None and linked:
                    row.account_id = linked
                if not row.stage:
                    row.stage = str(spec["stage"])
                continue
            session.add(
                EnvironmentRow(
                    id=str(spec["id"]), name=str(spec["name"]), kind=str(spec["kind"]), stage=str(spec["stage"]), method=str(spec["method"]),
                    target=str(spec["target"]), region=spec["region"], account_id=linked, external_id=None, secret_ref=None,  # type: ignore[arg-type]
                    auto_allow=list(spec["auto_allow"]), allowed_roles=list(spec["allowed_roles"]), health="unknown",  # type: ignore[arg-type]
                    version=str(spec["version"]), latency_ms=None, last_checked=None, seeded=True,
                )
            )

        # ---- xp rows ------------------------------------------------------------------------
        existing_xp = {row.agent for row in (await session.execute(select(XpRow))).scalars()}
        for agent in AGENT_IDS:
            if agent not in existing_xp:
                session.add(XpRow(agent=agent, total_xp=0, tasks_done=0, approvals_requested=0, updated_at=datetime.now(UTC)))

        # ---- seed runbooks ------------------------------------------------------------------
        seeded_titles = {row.title for row in (await session.execute(select(DocumentRow).where(DocumentRow.source == "seed"))).scalars()}
        for runbook in SEED_RUNBOOKS:
            if runbook["title"] in seeded_titles:
                continue
            chunks = [(chunk, hashed_embedding(chunk)) for chunk in chunk_text(runbook["content"])]
            await create_document(
                session, title=runbook["title"], source="seed", content=runbook["content"], tags=["runbook", *runbook.get("tags", [])],
                scope="global", embedding=hashed_embedding(runbook["content"]), created_by="system", chunks=chunks,
            )
